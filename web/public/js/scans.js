const noScans = new Map(Object.entries(NO_SCANS).map(([reporter, volumes]) => [reporter, new Set(volumes)]));

export const hasScans = (reporter, volume) => !noScans.get(reporter)?.has(String(volume));

export const noScansCount = () => [...noScans.values()].reduce((n, s) => n + s.size, 0);

// The 1-based page of the volume's PDF at METS ORDER `order` (CAP's first_page_order and
// last_page_order). The archival PDF has the volume METS's pages in ORDER, and every
// published volume's are 1 to N (each manifest's `pages.orders` is [[1, N]]), so the page
// is the ORDER. Anything else gives null, and the link opens the volume at its start.
export function pdfPage(order) {
  return Number.isSafeInteger(order) && order > 0 ? order : null;
}
